#!/usr/bin/env node
// Writes the seed scripts for the pathology dictionaries and the IHC assay catalog from the same sources the
// pilot uses, so the SQL database, the pilot and the C# rules start from identical data:
//
//   db/120_seed_pathology_dictionary.sql   from pilot/core/pathology.mjs (organs, diagnoses, distribution, laterality)
//                                          and pilot/core/defs.mjs (necropsy dictionaries and the three placeholder protocols)
//   db/130_seed_ihc_catalog.sql            from src/SeedData/ihc-assays.json (made by tools/ihc-import/convert_ihc_catalog.mjs)
//
//   node tools/seed-sql/generate_seed_sql.mjs
//
// The files are written as UTF-8 with a byte-order mark so sqlcmd and SSMS read names such as "β-gal" correctly.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import * as PATH from '../../pilot/core/pathology.mjs';
import { DICTIONARIES, PROTOCOLS } from '../../pilot/core/defs.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const lims = path.resolve(here, '..', '..');
const q = (v) => (v == null || v === '' ? 'NULL' : `N'${String(v).replace(/'/g, "''")}'`);
const bit = (b) => (b ? '1' : '0');
const write = (file, text) => { writeFileSync(path.join(lims, 'db', file), '﻿' + text.replace(/\n/g, '\r\n')); console.log(`Wrote db/${file}`); };

// ---------- 120: pathology dictionaries ----------
{
  const organs = [...PATH.ORGANS];
  for (const p of PROTOCOLS) for (const o of p.organs) if (!organs.includes(o.organ)) organs.push(o.organ);
  const L = [];
  L.push(`/* =============================================================================
   MHL LIMS  -  120_seed_pathology_dictionary.sql
   GENERATED by tools/seed-sql/generate_seed_sql.mjs from the pilot's dictionaries.
   Do not edit by hand; change pilot/core/pathology.mjs or defs.mjs and regenerate.

   PLACEHOLDER: a starter set in INHAND style so the system works before Zaphod's
   own dictionaries (tblOrgans, tblDiagnosis, tblSeverity, tblDistribution,
   tblNeoplasm, tblHN ...) are migrated (open question 21). Idempotent.
   ============================================================================= */
SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;
`);
  L.push(`MERGE ref.Organ AS t
USING (VALUES
${organs.map((o, i) => `    (${q(o)}, ${bit(PATH.PAIRED.has(o))}, ${(i + 1) * 10})`).join(',\n')}
) AS s (OrganCode, IsPaired, SortOrder)
ON t.OrganCode = s.OrganCode
WHEN MATCHED THEN UPDATE SET IsPaired = s.IsPaired, SortOrder = s.SortOrder
WHEN NOT MATCHED THEN INSERT (OrganCode, IsPaired, SortOrder) VALUES (s.OrganCode, s.IsPaired, s.SortOrder);
`);
  const terms = [
    ...DICTIONARIES.sites.map((t) => ['NECROPSY_SITE', t]), ...DICTIONARIES.morphology.map((t) => ['MORPHOLOGY', t]),
    ...DICTIONARIES.shapes.map((t) => ['SHAPE', t]), ...DICTIONARIES.colors.map((t) => ['COLOR', t]),
    ...DICTIONARIES.consistencies.map((t) => ['CONSISTENCY', t]), ...DICTIONARIES.fates.map((t) => ['FATE', t]),
    ...DICTIONARIES.conditions.map((t) => ['CONDITION', t]), ...DICTIONARIES.physicalIds.map((t) => ['PHYSICAL_ID', t]),
    ...PATH.DISTRIBUTION.map((t) => ['DISTRIBUTION', t]), ...PATH.LATERALITY.map((t) => ['LATERALITY', t]),
  ];
  const order = {};
  L.push(`MERGE ref.DictionaryTerm AS t
USING (VALUES
${terms.map(([d, t]) => { order[d] = (order[d] || 0) + 10; return `    (N'${d}', ${q(t)}, ${order[d]})`; }).join(',\n')}
) AS s (DictionaryCode, Term, SortOrder)
ON t.DictionaryCode = s.DictionaryCode AND t.Term = s.Term
WHEN MATCHED THEN UPDATE SET SortOrder = s.SortOrder
WHEN NOT MATCHED THEN INSERT (DictionaryCode, Term, SortOrder) VALUES (s.DictionaryCode, s.Term, s.SortOrder);
`);
  L.push(`MERGE ref.Diagnosis AS t
USING (VALUES
${PATH.DIAGNOSES.map((x) => `    (${q(x.term)}, ${bit(x.neoplasm)}, ${bit(x.organs[0] === '*')})`).join(',\n')}
) AS s (Term, IsNeoplasm, IsGeneral)
ON t.Term = s.Term
WHEN MATCHED THEN UPDATE SET IsNeoplasm = s.IsNeoplasm, IsGeneral = s.IsGeneral
WHEN NOT MATCHED THEN INSERT (Term, IsNeoplasm, IsGeneral) VALUES (s.Term, s.IsNeoplasm, s.IsGeneral);
`);
  const pairs = PATH.DIAGNOSES.filter((x) => x.organs[0] !== '*').flatMap((x) => x.organs.map((o) => [x.term, o]));
  L.push(`INSERT INTO ref.DiagnosisOrgan (DiagnosisId, OrganCode)
SELECT d.DiagnosisId, s.OrganCode
FROM (VALUES
${pairs.map(([t, o]) => `    (${q(t)}, ${q(o)})`).join(',\n')}
) AS s (Term, OrganCode)
JOIN ref.Diagnosis AS d ON d.Term = s.Term
WHERE NOT EXISTS (SELECT 1 FROM ref.DiagnosisOrgan x WHERE x.DiagnosisId = d.DiagnosisId AND x.OrganCode = s.OrganCode);
`);
  L.push(`-- The pilot's three necropsy protocols (PLACEHOLDER until Zaphod's protocols are migrated).`);
  for (const p of PROTOCOLS) {
    L.push(`IF NOT EXISTS (SELECT 1 FROM path.NecropsyProtocol WHERE Name = ${q(p.name)})
BEGIN
    INSERT INTO path.NecropsyProtocol (Name, WeighAnimal, Perfusion, IsApproved) VALUES (${q(p.name)}, ${bit(p.bodyWeight)}, ${p.perfusion ? q(p.perfusion.toUpperCase()) : 'NULL'}, 0);
    DECLARE @p${p.id} int = SCOPE_IDENTITY();
    INSERT INTO path.NecropsyProtocolOrgan (ProtocolId, Sequence, OrganCode, WeighOrgan, DefaultBlock) VALUES
${p.organs.map((o, i) => `        (@p${p.id}, ${i + 1}, ${q(o.organ)}, ${bit(o.weigh)}, ${q(String(o.block))})`).join(',\n')};
END`);
  }
  L.push(`
COMMIT TRANSACTION;
PRINT N'Pathology dictionaries seeded: ${organs.length} organs, ${PATH.DIAGNOSES.length} diagnoses, ${terms.length} dictionary terms, ${PROTOCOLS.length} protocols.';
GO
`);
  write('120_seed_pathology_dictionary.sql', L.join('\n'));
}

// ---------- 130: IHC assay catalog ----------
{
  const cat = JSON.parse(readFileSync(path.join(lims, 'src', 'SeedData', 'ihc-assays.json'), 'utf8'));
  const KIND = { IHC: 'IHC', Opal: 'OPAL', IF: 'IF', TUNEL: 'TUNEL', 'β-gal': 'BETA_GAL' };
  const FLAG = (f) => f.toUpperCase().replace(/-/g, '_');
  const A = cat.assays;
  const L = [];
  L.push(`/* =============================================================================
   MHL LIMS  -  130_seed_ihc_catalog.sql
   GENERATED by tools/seed-sql/generate_seed_sql.mjs from src/SeedData/ihc-assays.json
   (${A.length} catalog entries converted from "${cat.source}" on ${cat.convertedOn}).
   Do not edit by hand. Runs only on an empty catalog.

   Assay IDs are kept from the pilot (#1, #2 ...) so requests made in the pilot
   and docs/ihc-catalog-review.md still match. When the phlrequest database
   itself is migrated, its keys go in ihc.Assay.LegacyAssayKey.
   ============================================================================= */
SET NOCOUNT ON;
SET XACT_ABORT ON;
IF EXISTS (SELECT 1 FROM ihc.Assay)
BEGIN
    PRINT N'ihc.Assay already has rows; the catalog seed was skipped.';
    RETURN;
END
BEGIN TRANSACTION;
SET IDENTITY_INSERT ihc.Assay ON;
`);
  // Duplicates are inserted ACTIVE and marked afterwards, so their originals always exist first.
  const cols = 'AssayId, Name, Dilution, AntigenRetrieval, ProteolyticDigestion, DetectionKit, Fixative, Species, ControlTissue, Manufacturer, CatalogNumber, Kind, Plex, Chromogen, Platform, Status, Notes, SourceReference';
  for (let i = 0; i < A.length; i += 100) {
    L.push(`INSERT INTO ihc.Assay (${cols}) VALUES`);
    L.push(A.slice(i, i + 100).map((a) => {
      const src = a.components ? `DOUBLE STAIN marker at line ${a.sourceLine}` : a.sourceLine ? `${cat.source} line ${a.sourceLine}${a.list ? `, list ${a.list}` : ''}` : null;
      return `    (${a.id}, ${q(a.name)}, ${q(a.dilution)}, ${q(a.retrieval)}, ${q(a.digestion)}, ${q(a.kit)}, ${q(a.fixative)}, ${q(a.species)}, ${q(a.control)}, ${q(a.manufacturer)}, ${q(a.catalog)}, N'${KIND[a.kind]}', ${a.plex || 1}, ${q(a.chromogen || 'DAB')}, ${q(a.platform || 'Manual')}, ${a.status === 'Retired' ? "N'RETIRED'" : "N'ACTIVE'"}, ${q(a.notes)}, ${q(src)})`;
    }).join(',\n') + ';');
  }
  L.push('SET IDENTITY_INSERT ihc.Assay OFF;\n');
  const dups = A.filter((a) => a.status === 'Duplicate');
  if (dups.length) L.push(`UPDATE a SET Status = N'DUPLICATE', DuplicateOfAssayId = s.DuplicateOf
FROM ihc.Assay AS a JOIN (VALUES ${dups.map((a) => `(${a.id}, ${a.duplicateOf})`).join(', ')}) AS s (AssayId, DuplicateOf) ON s.AssayId = a.AssayId;
`);
  const comps = A.filter((a) => a.components).flatMap((a) => a.components.map((c, i) => `(${a.id}, ${c}, ${i + 1})`));
  if (comps.length) L.push(`INSERT INTO ihc.AssayComponent (AssayId, ComponentAssayId, StainOrder) VALUES\n    ${comps.join(',\n    ')};\n`);
  const sp = A.flatMap((a) => (a.speciesTags || []).map((t) => `(${a.id}, ${q(t)})`));
  for (let i = 0; i < sp.length; i += 500) L.push(`INSERT INTO ihc.AssaySpeciesTag (AssayId, Tag) VALUES\n    ${sp.slice(i, i + 500).join(',\n    ')};\n`);
  const fx = A.flatMap((a) => (a.fixTags || []).map((t) => `(${a.id}, ${q(t)})`));
  for (let i = 0; i < fx.length; i += 500) L.push(`INSERT INTO ihc.AssayFixativeTag (AssayId, Tag) VALUES\n    ${fx.slice(i, i + 500).join(',\n    ')};\n`);
  const fl = A.flatMap((a) => (a.flags || []).map((f) => `(${a.id}, N'${FLAG(f)}', ${q(f === 'dilution-recovered' ? a.repairs?.dilution : f === 'name-recovered' ? a.repairs?.name : null)})`));
  for (let i = 0; i < fl.length; i += 500) L.push(`INSERT INTO ihc.AssayFlag (AssayId, FlagCode, StoredValue) VALUES\n    ${fl.slice(i, i + 500).join(',\n    ')};\n`);
  L.push(`COMMIT TRANSACTION;
PRINT N'IHC catalog seeded: ${A.length} assays (${A.filter((a) => a.components).length} double stains, ${dups.length} duplicates), ${fl.length} review flags.';
GO
`);
  write('130_seed_ihc_catalog.sql', L.join('\n'));
}
