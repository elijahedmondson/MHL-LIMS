-- 1. what was copied
SELECT t.name AS StageTable,
       SUM(CASE WHEN p.index_id IN (0,1) THEN p.row_count ELSE 0 END) AS [RowCount]
FROM sys.tables AS t
JOIN sys.dm_db_partition_stats AS p ON p.object_id = t.object_id
WHERE t.schema_id = SCHEMA_ID(N'stage')
GROUP BY t.name
ORDER BY t.name;

-- 2. what is missing
SELECT r.StageTable, r.ColumnName, r.Basis,
       CASE WHEN OBJECT_ID(N'stage.' + r.StageTable) IS NULL THEN N'TABLE NOT COPIED' ELSE N'COLUMN MISSING' END AS Problem
INTO #missing
FROM @required AS r
LEFT JOIN INFORMATION_SCHEMA.COLUMNS AS c
       ON c.TABLE_SCHEMA = N'stage' AND c.TABLE_NAME = r.StageTable AND c.COLUMN_NAME = r.ColumnName
WHERE c.COLUMN_NAME IS NULL;

SELECT * FROM #missing ORDER BY Problem, StageTable, ColumnName;

-- Which loader scripts can run? PHL scripts need the PHL_ tables; Zaphod scripts need the ZAP_ tables.
SELECT CASE WHEN StageTable LIKE N'PHL[_]%' THEN N'PHL (scripts 100-130)' ELSE N'ZAPHOD (scripts 200-230)' END AS LoaderGroup,
       COUNT(*) AS MissingItems,
       SUM(CASE WHEN Basis = N'KNOWN' OR Problem = N'TABLE NOT COPIED' THEN 1 ELSE 0 END) AS Blocking
FROM #missing
GROUP BY CASE WHEN StageTable LIKE N'PHL[_]%' THEN N'PHL (scripts 100-130)' ELSE N'ZAPHOD (scripts 200-230)' END;

IF EXISTS (SELECT 1 FROM #missing)
    PRINT N'Some expected tables or columns are missing; see the second result set. Do not run the loaders for a group with blocking items.';
ELSE
    PRINT N'All expected stage tables and columns are present.';
DROP TABLE #missing;
GO
